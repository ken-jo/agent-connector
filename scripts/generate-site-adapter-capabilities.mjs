/**
 * Generate the public-site adapter capability snapshot from the real registry.
 *
 * The site intentionally keeps human-authored host-native provenance in
 * site/src/platform-data.ts, but the "what agent-connector installs today"
 * support profile should come from src/adapters/* instead of being recopied in
 * docs prose. This script loads the TypeScript registry through tsx and writes a
 * small dependency-free TS data module consumed by the coverage/docs pages.
 */

import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const scriptFile = fileURLToPath(import.meta.url);
const repoRoot = path.resolve(path.dirname(scriptFile), "..");
const outFile = path.join(repoRoot, "site", "src", "adapter-capabilities.generated.ts");

function resolveTsxImport() {
  const requireFromRoot = createRequire(import.meta.url);
  const requireFromSite = createRequire(path.join(repoRoot, "site", "package.json"));

  for (const requireFrom of [requireFromRoot, requireFromSite]) {
    try {
      return pathToFileURL(requireFrom.resolve("tsx")).href;
    } catch {
      // Try the next install layout.
    }
  }

  throw new Error("Unable to resolve tsx. Run npm ci in the repository root or site directory.");
}

if (process.env.AGENT_CONNECTOR_CAPABILITY_GENERATOR_TSX !== "1") {
  const result = spawnSync(process.execPath, ["--import", resolveTsxImport(), scriptFile], {
    cwd: repoRoot,
    env: {
      ...process.env,
      AGENT_CONNECTOR_CAPABILITY_GENERATOR_TSX: "1",
    },
    stdio: "inherit",
  });
  process.exit(result.status ?? 1);
}

const { ADAPTER_REGISTRY } = await import("../src/adapters/registry.ts");

const surfaceKeys = [
  "mcp",
  "hooks",
  "commands",
  "skills",
  "subagents",
  "memory",
  "statusline",
  "actions",
];

function surfacesFor(adapter) {
  const caps = adapter.capabilities;
  return {
    mcp: caps.transports.length > 0,
    hooks: adapter.paradigm !== "mcp-only",
    commands: caps.supportsCommands ?? false,
    skills: caps.supportsSkills ?? false,
    subagents: caps.supportsSubagents ?? false,
    memory: caps.supportsMemory ?? false,
    statusline: caps.supportsStatusline ?? false,
    actions: caps.supportsActions ?? false,
  };
}

const profiles = [];
for (const factory of ADAPTER_REGISTRY) {
  const adapter = await factory.load();
  profiles.push({
    id: factory.id,
    name: adapter.name,
    paradigm: adapter.paradigm,
    surfaces: surfacesFor(adapter),
  });
}

const content = `/**
 * adapter-capabilities.generated — generated by scripts/generate-site-adapter-capabilities.mjs.
 *
 * Do not edit by hand. This is the public-site snapshot of what the adapter
 * registry says agent-connector installs today. Human-authored host-native
 * provenance stays in site/src/platform-data.ts.
 */

export type GeneratedParadigmId = "json-stdio" | "mcp-only" | "ts-plugin";

export type GeneratedSurfaceKey =
  | "mcp"
  | "hooks"
  | "commands"
  | "skills"
  | "subagents"
  | "memory"
  | "statusline"
  | "actions";

export interface GeneratedPlatformSurfaces {
  mcp: boolean;
  hooks: boolean;
  commands: boolean;
  skills: boolean;
  subagents: boolean;
  memory: boolean;
  statusline: boolean;
  actions: boolean;
}

export interface GeneratedAdapterCapabilityProfile {
  id: string;
  name: string;
  paradigm: GeneratedParadigmId;
  surfaces: GeneratedPlatformSurfaces;
}

export const generatedSurfaceKeys = ${JSON.stringify(surfaceKeys, null, 2)} as const satisfies readonly GeneratedSurfaceKey[];

export const generatedSurfaceLabels: Record<GeneratedSurfaceKey, string> = {
  mcp: "MCP",
  hooks: "Hooks",
  commands: "Commands",
  skills: "Skills",
  subagents: "Subagents",
  memory: "Memory",
  statusline: "Statusline",
  actions: "Actions",
};

export const adapterCapabilityProfiles = ${JSON.stringify(profiles, null, 2)} as const satisfies readonly GeneratedAdapterCapabilityProfile[];

export const adapterCapabilityCount = adapterCapabilityProfiles.length;
`;

writeFileSync(outFile, content);
console.log(`[capabilities] wrote ${path.relative(repoRoot, outFile)} — ${profiles.length} adapters`);
