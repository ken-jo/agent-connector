/**
 * Generate the public-site host verification snapshot from the committed CSV.
 *
 * docs/host-verification-results.csv is the human-readable evidence ledger.
 * The site consumes a typed, dependency-free TS module generated from that CSV
 * so coverage pages can show the verification ladder without duplicating rows.
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const csvFile = path.join(repoRoot, "docs", "host-verification-results.csv");
const outFile = path.join(repoRoot, "site", "src", "host-verification.generated.ts");

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let inQuotes = false;

  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    const next = text[i + 1];

    if (ch === '"') {
      if (inQuotes && next === '"') {
        field += '"';
        i++;
      } else {
        inQuotes = !inQuotes;
      }
      continue;
    }

    if (ch === "," && !inQuotes) {
      row.push(field);
      field = "";
      continue;
    }

    if ((ch === "\n" || ch === "\r") && !inQuotes) {
      if (ch === "\r" && next === "\n") i++;
      row.push(field);
      if (row.some((value) => value.length > 0)) rows.push(row);
      row = [];
      field = "";
      continue;
    }

    field += ch;
  }

  if (field.length > 0 || row.length > 0) {
    row.push(field);
    if (row.some((value) => value.length > 0)) rows.push(row);
  }

  return rows;
}

const parsed = parseCsv(readFileSync(csvFile, "utf8"));
const [header, ...records] = parsed;

const expectedHeader = [
  "host",
  "install_probe",
  "doctor_probe",
  "host_cli_surface",
  "headless_model_mcp_e2e",
  "result",
  "issue_or_blocker",
  "evidence",
];

if (!header || header.join("|") !== expectedHeader.join("|")) {
  throw new Error(`[verification] unexpected CSV header in ${csvFile}`);
}

const rows = records.map((record) => {
  if (record.length !== expectedHeader.length) {
    throw new Error(`[verification] malformed row: ${JSON.stringify(record)}`);
  }
  const [
    host,
    installProbe,
    doctorProbe,
    hostCliSurface,
    headlessModelMcpE2e,
    result,
    issueOrBlocker,
    evidence,
  ] = record;
  return {
    host,
    installProbe,
    doctorProbe,
    hostCliSurface,
    headlessModelMcpE2e,
    result,
    issueOrBlocker,
    evidence,
  };
});

const content = `/**
 * host-verification.generated — generated by scripts/generate-site-verification-results.mjs.
 *
 * Do not edit by hand. The source ledger is docs/host-verification-results.csv.
 */

export type VerificationLevelId = "e2e" | "live-runtime" | "live-accept" | "live-placement" | "adapter-placement" | "install-doctor";

export interface HostVerificationResult {
  host: string;
  installProbe: string;
  doctorProbe: string;
  hostCliSurface: string;
  headlessModelMcpE2e: string;
  result: string;
  issueOrBlocker: string;
  evidence: string;
}

export const verificationLevelOrder = [
  "e2e",
  "live-runtime",
  "live-accept",
  "live-placement",
  "adapter-placement",
  "install-doctor",
] as const satisfies readonly VerificationLevelId[];

export const verificationLevelLabels: Record<VerificationLevelId, string> = {
  e2e: "E2E",
  "live-runtime": "Live runtime",
  "live-accept": "Live accept",
  "live-placement": "Live placement",
  "adapter-placement": "Adapter placement",
  "install-doctor": "Install + doctor",
};

export const verificationLevelDescriptions: Record<VerificationLevelId, string> = {
  e2e: "A real host advanced a model turn and the MCP tool call was observed.",
  "live-runtime": "A real host advanced a headless runtime and fired hooks or loaded MCP, but no model MCP tool-call E2E was observed.",
  "live-accept": "The host accepted or listed the installed MCP config, but auth or model access blocked the final turn.",
  "live-placement": "A real host CLI was installed and driven far enough to verify native placement plus uninstall cleanup, but no offline accept/runtime lane exists.",
  "adapter-placement": "No local host CLI can be driven, but the supported adapter was installed into an isolated HOME/project and cleanly uninstalled.",
  "install-doctor": "Placement, dry install, doctor, and uninstall hygiene are verified; no login-free headless runtime lane is available.",
};

export function verificationLevelForResult(result: string): VerificationLevelId {
  if (result === "VERIFIED_E2E") return "e2e";
  if (result === "LIVE_RUNTIME_VERIFIED") return "live-runtime";
  if (result === "MCP_INSTALL_VERIFIED_AUTH_BLOCKED") return "live-accept";
  if (result === "INSTALL_DOCTOR_VERIFIED_NO_HEADLESS_MODE") return "live-placement";
  if (result === "ADAPTER_PLACEMENT_VERIFIED") return "adapter-placement";
  return "install-doctor";
}

export const hostVerificationResults = ${JSON.stringify(rows, null, 2)} as const satisfies readonly HostVerificationResult[];

export const hostVerificationCount = hostVerificationResults.length;
`;

writeFileSync(outFile, content);
console.log(`[verification] wrote ${path.relative(repoRoot, outFile)} — ${rows.length} hosts`);
