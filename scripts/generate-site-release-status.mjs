/**
 * Generate the public-site release hygiene snapshot.
 *
 * The site should expose the local package version, npm latest, GitHub latest
 * release, and whether CI/deploy workflow files are present without making the
 * React app call live services at runtime. Network calls are best-effort; on a
 * registry/API failure the previous committed snapshot is preserved, and the
 * local package/workflow facts are still refreshed.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.join(repoRoot, "site", "src", "release-status.generated.ts");
const pkgFile = path.join(repoRoot, "package.json");
const ciWorkflowFile = path.join(repoRoot, ".github", "workflows", "ci.yml");
const deployWorkflowFile = path.join(repoRoot, ".github", "workflows", "deploy-site.yml");

const pkg = JSON.parse(readFileSync(pkgFile, "utf8"));
const packageName = typeof pkg.name === "string" ? pkg.name : "@ken-jo/agent-connector";
const localVersion = typeof pkg.version === "string" ? pkg.version : "0.0.0";
const repoUrl =
  typeof pkg.repository?.url === "string"
    ? pkg.repository.url
        .replace(/^git\+/, "")
        .replace(/\.git$/, "")
    : "https://github.com/ken-jo/agent-connector";
const npmPackageUrl = `https://www.npmjs.com/package/${packageName}`;
const githubActionsUrl = `${repoUrl}/actions`;
const ciWorkflowUrl = `${repoUrl}/actions/workflows/ci.yml`;
const deployWorkflowUrl = `${repoUrl}/actions/workflows/deploy-site.yml`;

function loadPrevious() {
  if (!existsSync(outFile)) return {};
  const text = readFileSync(outFile, "utf8");
  const marker = "export const releaseStatus = ";
  const start = text.indexOf(marker);
  if (start === -1) return {};
  const jsonStart = start + marker.length;
  const jsonEnd = text.indexOf(" as const satisfies ReleaseStatus;", jsonStart);
  if (jsonEnd === -1) return {};
  try {
    return JSON.parse(text.slice(jsonStart, jsonEnd));
  } catch {
    return {};
  }
}

async function fetchJson(url, headers = {}) {
  const res = await fetch(url, {
    headers: {
      Accept: "application/json",
      "User-Agent": "agent-connector-site-build",
      ...headers,
    },
  });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  return res.json();
}

const previous = loadPrevious();

let npmLatest = previous.npmLatest ?? null;
let npmPublishedAt = previous.npmPublishedAt ?? null;
let npmFetchStatus = "fallback";
try {
  const escaped = encodeURIComponent(packageName).replace("%40", "@");
  const npm = await fetchJson(`https://registry.npmjs.org/${escaped}`);
  npmLatest = typeof npm?.["dist-tags"]?.latest === "string" ? npm["dist-tags"].latest : null;
  npmPublishedAt =
    npmLatest && typeof npm?.time?.[npmLatest] === "string" ? npm.time[npmLatest] : null;
  npmFetchStatus = "ok";
} catch (err) {
  npmFetchStatus = `fallback:${String(err.message ?? err)}`;
}

let githubLatest = previous.githubLatest ?? null;
let githubReleaseUrl = previous.githubReleaseUrl ?? `${repoUrl}/releases`;
let githubPublishedAt = previous.githubPublishedAt ?? null;
let githubFetchStatus = "fallback";
try {
  const token = process.env.GITHUB_TOKEN || process.env.GH_TOKEN || "";
  const release = await fetchJson("https://api.github.com/repos/ken-jo/agent-connector/releases/latest", {
    ...(token ? { Authorization: `Bearer ${token}` } : {}),
    Accept: "application/vnd.github+json",
  });
  githubLatest = typeof release?.tag_name === "string" ? release.tag_name : null;
  githubReleaseUrl =
    typeof release?.html_url === "string" ? release.html_url : `${repoUrl}/releases`;
  githubPublishedAt =
    typeof release?.published_at === "string" ? release.published_at : null;
  githubFetchStatus = "ok";
} catch (err) {
  githubFetchStatus = `fallback:${String(err.message ?? err)}`;
}

const status = {
  packageName,
  localVersion,
  npmLatest,
  npmPublishedAt,
  npmPackageUrl,
  npmFetchStatus,
  githubLatest,
  githubReleaseUrl,
  githubPublishedAt,
  githubFetchStatus,
  repoUrl,
  githubActionsUrl,
  ciWorkflow: {
    present: existsSync(ciWorkflowFile),
    path: ".github/workflows/ci.yml",
    url: ciWorkflowUrl,
  },
  deployWorkflow: {
    present: existsSync(deployWorkflowFile),
    path: ".github/workflows/deploy-site.yml",
    url: deployWorkflowUrl,
  },
};

const content = `/**
 * release-status.generated — generated by scripts/generate-site-release-status.mjs.
 *
 * Do not edit by hand. Live registry/API lookups are best-effort; failed remote
 * reads keep the previous snapshot while local package/workflow facts refresh.
 */

export interface ReleaseWorkflowStatus {
  present: boolean;
  path: string;
  url: string;
}

export interface ReleaseStatus {
  packageName: string;
  localVersion: string;
  npmLatest: string | null;
  npmPublishedAt: string | null;
  npmPackageUrl: string;
  npmFetchStatus: string;
  githubLatest: string | null;
  githubReleaseUrl: string;
  githubPublishedAt: string | null;
  githubFetchStatus: string;
  repoUrl: string;
  githubActionsUrl: string;
  ciWorkflow: ReleaseWorkflowStatus;
  deployWorkflow: ReleaseWorkflowStatus;
}

export const releaseStatus = ${JSON.stringify(status, null, 2)} as const satisfies ReleaseStatus;
`;

writeFileSync(outFile, content);
console.log(
  `[release] wrote ${path.relative(repoRoot, outFile)} — local ${localVersion}, npm ${npmLatest ?? "unknown"}, GitHub ${githubLatest ?? "unknown"}`,
);
